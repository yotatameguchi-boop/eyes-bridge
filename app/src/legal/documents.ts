/** GitHub で読める Markdown にする（docs/legal/ を作る。手で直さない） */
export function toMarkdown(doc: LegalDocument): string {
  const lines = [
    `# ${doc.title}`,
    "",
    `版：${doc.version}`,
    "",
    "> これは下書きです。【要記入】【要確認】は運営者が決める箇所です。",
    "> 公開する前に、必ず専門家（弁護士など）に確認してもらってください。",
    ">",
    "> このファイルは app/src/legal/documents.ts から作っています。直すときはそちらを直し、",
    "> `cd app && npm run legal:docs` で作り直してください。",
    "",
    "## 要点",
    "",
    ...doc.summary.map((s) => `- ${s}`),
    "",
  ];
  for (const section of doc.sections) {
    lines.push(`## ${section.heading}`, "");
    for (const p of section.paragraphs) lines.push(p, "");
  }
  return lines.join("\n");
}
