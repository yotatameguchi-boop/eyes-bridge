// 読み上げる内容によって、先に添える注意。
//
// 薬の飲む量や回数は、読み間違えると命に関わる。OCR は「自信満々で
// 読み間違える」ことがあり、自信の低い行への警告だけでは防げない。
// 薬の説明らしいときは、読む前に「人にも確かめて」と必ず言う。
//
// 判定は緩めにしてある。薬なのに言わない（見逃し）のほうが、
// 薬でないのに言う（言い過ぎ）より危ないため。
// ただし「薬味」のように、薬と関係ない語で鳴らないようにはする。

// これが1つでもあれば薬の説明とみなす
const MEDICINE_WORDS =
  /用法|用量|服用|内服|頓服|外用|処方|調剤|薬剤|お薬|医薬品|目薬|飲み薬|塗り薬|粉薬|水薬|抗生|解熱|鎮痛/;

// 量（「2錠」「500mg」など）と、飲むタイミング（「食後」「1日3回」など）が
// 両方あれば薬の説明とみなす。片方だけだと、献立や時刻表でも出てくる。
const DOSE = /\d+(\.\d+)?\s*(錠|カプセル|包|滴|mg|ｍｇ|ミリグラム|mL|ml|ミリリットル)/;
const TIMING = /食前|食後|食間|就寝前|起床時|寝る前|[1１]日\s*[0-9０-９一二三四]+\s*回|[0-9０-９]+\s*時間(毎|ごと|おき)/;

export function looksLikeMedicine(text: string): boolean {
  if (MEDICINE_WORDS.test(text)) return true;
  return DOSE.test(text) && TIMING.test(text);
}

